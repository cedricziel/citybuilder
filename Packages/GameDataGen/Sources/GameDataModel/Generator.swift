import Foundation

public enum Generator {
    /// Loads and validates the game data, then writes the generated Swift
    /// and returns the written file names. Writes nothing when validation
    /// fails. A `namespace` is passed on to `SwiftEmitter.emit`.
    public static func generate(
        dataDirectory: URL, outputDirectory: URL, namespace: String? = nil
    ) -> Result<[String], GameDataErrors> {
        GameDataLoader.load(from: DirectorySource(root: dataDirectory)).flatMap { data in
            let files = SwiftEmitter.emit(data, namespace: namespace)
            do {
                try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
                try removeStaleFiles(in: outputDirectory, keeping: Set(files.keys))
                for (name, text) in files {
                    try Data(text.utf8).write(to: outputDirectory.appendingPathComponent(name), options: .atomic)
                }
            } catch {
                let failure = Diagnostic(origin: Origin(file: outputDirectory.path), message: "cannot write: \(error)")
                return .failure(GameDataErrors(diagnostics: [failure]))
            }
            return .success(files.keys.sorted())
        }
    }

    /// Deletes Swift files a previous run generated and this run does not,
    /// recognised by the first line of the banner. Other files stay.
    private static func removeStaleFiles(in directory: URL, keeping names: Set<String>) throws {
        let present = try FileManager.default.contentsOfDirectory(atPath: directory.path)
        for name in present where name.hasSuffix(".swift") && !names.contains(name) {
            let file = directory.appendingPathComponent(name)
            if let text = try? String(contentsOf: file, encoding: .utf8), text.hasPrefix("// GENERATED by gamedata-gen") {
                try FileManager.default.removeItem(at: file)
            }
        }
    }
}
